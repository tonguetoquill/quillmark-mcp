#!/usr/bin/env node
// Renders a date-stamped Markdown REPORT from one or more JSONL result files,
// summarizing individual (per-model) and cross-model (per-prompt grid +
// systematic failures) performance. Reuses the aggregation logic in report.js
// so the numbers match the live stdout report exactly.
//
//   node eval/make-report.js eval/results/*.jsonl            # -> eval/reports/REPORT-<date>.md
//   node eval/make-report.js --out FILE eval/results/*.jsonl
//
// Reports are canonically written to eval/reports/ (created on demand). The
// date stamp comes from the latest run timestamp in the data (falling back to
// today) so the filename reflects when the fleet was actually evaluated.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';

import {
  summarize,
  summarizeByPrompt,
  systematicFailures,
  classifyOutcome,
} from './report.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));

function loadJsonl(file) {
  return readFileSync(file, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l));
}

const pct = (x) => (x == null ? '—' : (x * 100).toFixed(0) + '%');
const num = (x, d = 1) => (x == null ? '—' : Number(x).toFixed(d));
const dur = (ms) => (ms == null || ms === 0 ? '—' : ms >= 1000 ? (ms / 1000).toFixed(1) + 's' : Math.round(ms) + 'ms');
const tok = (x) => (x == null ? '—' : x >= 1000 ? (x / 1000).toFixed(1) + 'k' : String(Math.round(x)));

function topMap(obj, n = 4) {
  const e = Object.entries(obj ?? {}).filter(([, v]) => v > 0).sort((a, b) => b[1] - a[1]).slice(0, n);
  return e.length ? e.map(([k, v]) => `${k}×${v}`).join(', ') : '—';
}

// Cross-model success per prompt cell: "67% (n=9)".
function gridCell(cell) {
  if (!cell) return '—';
  return `${pct(cell.successRate)}`;
}

function build(records, dateStamp) {
  // Rank by success, then break ties by cleaner success (more one-shot, fewer
  // attempts) so a 4-way 100% tie still has a meaningful order.
  const models = summarize(records).sort((a, b) =>
    b.successRate - a.successRate
    || b.oneShotRate - a.oneShotRate
    || (a.attemptsMean ?? 99) - (b.attemptsMean ?? 99));
  const grid = summarizeByPrompt(records);
  const sysFail = systematicFailures(records);

  const totalRuns = records.length;
  const totalSuccess = records.filter((r) => r.success).length;
  const infra = records.filter((r) => classifyOutcome(r) === 'infra').length;
  const llm = records.filter((r) => classifyOutcome(r) === 'llm').length;
  const totalTokens = records.reduce((a, r) => a + (r.totalTokens ?? 0), 0);
  const modelNames = grid.models;

  const L = [];
  L.push(`# Open-Source Model Eval Report — ${dateStamp}`);
  L.push('');
  L.push('Fleet evaluation of the `quillmark-mcp` MCP flow ergonomics: how reliably each');
  L.push('open-weight model can drive the `list_quills → get_spec → create_document` loop');
  L.push('and recover from render diagnostics. Success = `create_document` returned');
  L.push('non-error (no quality judge). Generated by `eval/make-report.js` from the raw');
  L.push('JSONL in `eval/results/`.');
  L.push('');
  L.push('## Run scope');
  L.push('');
  L.push(`- **Models:** ${modelNames.length}`);
  L.push(`- **Prompts:** ${grid.prompts.length} (${grid.prompts.join(', ')})`);
  L.push(`- **Total runs:** ${totalRuns}`);
  L.push(`- **Overall success:** ${totalSuccess}/${totalRuns} (${pct(totalSuccess / totalRuns)})`);
  L.push(`- **Outcome split:** success ${pct(totalSuccess / totalRuns)} · llm-fail ${pct(llm / totalRuns)} · infra ${pct(infra / totalRuns)}`);
  L.push(`- **Tokens consumed:** ${tok(totalTokens)}`);
  L.push('');

  // ── Individual performance ────────────────────────────────────────────────
  L.push('## Individual model performance');
  L.push('');
  L.push('Sorted by success rate. `att` = mean/max create_document attempts to success.');
  L.push('`specs1st` = fraction that called `get_spec` before `create_document`.');
  L.push('`chain` = fraction that drove the whole `list_quills? → get_spec →');
  L.push('create_document` chain in the prescribed order (of runs that reached');
  L.push('create_document). `1-shot` = succeeded on first create attempt.');
  L.push('`self-corr` = of successes, fraction needing >1 attempt (diagnostics doing');
  L.push('real work).');
  L.push('');
  L.push('| Model | n | success | llm-fail | infra | att | specs1st | chain | 1-shot | self-corr | tools | tokens | time |');
  L.push('|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|');
  for (const m of models) {
    L.push(`| \`${m.model}\` | ${m.total} | ${pct(m.successRate)} | ${pct(m.llmRate)} | ${pct(m.infraRate)} | ${num(m.attemptsMean)}/${m.attemptsMax ?? '—'} | ${pct(m.specsBeforeCreateRate)} | ${pct(m.toolChainRate)} | ${pct(m.oneShotRate)} | ${pct(m.selfCorrectionRate)} | ${num(m.meanToolCalls)} | ${tok(m.meanTokens)} | ${dur(m.meanDurationMs)} |`);
  }
  L.push('');
  L.push('### Per-model error & termination breakdown');
  L.push('');
  for (const m of models) {
    L.push(`- **\`${m.model}\`** — errors: ${topMap(m.errorCategories)}; termination: ${topMap(m.terminationReasons)}`);
  }
  L.push('');

  // ── Cross-model performance ───────────────────────────────────────────────
  L.push('## Cross-model performance (per-prompt success grid)');
  L.push('');
  L.push('Success rate of each model on each prompt. Reading down a column profiles a');
  L.push('model; reading across a row profiles a prompt/quill (low across-the-board ⇒');
  L.push('likely a quill/spec issue, not a model weakness).');
  L.push('');
  const shortNames = modelNames.map((n) => (n.includes('/') ? n.split('/').slice(1).join('/') : n));
  L.push('| prompt | quill | ' + shortNames.join(' | ') + ' |');
  L.push('|---|---|' + modelNames.map(() => '--:').join('|') + '|');
  for (const p of grid.prompts) {
    const row = grid.grid[p];
    const cells = modelNames.map((m) => gridCell(row.byModel[m]));
    L.push(`| ${p} | ${row.meta.quill ?? '—'} | ${cells.join(' | ')} |`);
  }
  // Per-prompt aggregate (across all models) row.
  L.push('');
  L.push('### Per-prompt aggregate (all models)');
  L.push('');
  L.push('| prompt | quill | success | runs |');
  L.push('|---|---|--:|--:|');
  for (const p of grid.prompts) {
    const runs = records.filter((r) => r.promptId === p);
    const ok = runs.filter((r) => r.success).length;
    L.push(`| ${p} | ${grid.grid[p].meta.quill ?? '—'} | ${pct(ok / runs.length)} | ${ok}/${runs.length} |`);
  }
  L.push('');

  // ── Systematic failures ───────────────────────────────────────────────────
  L.push('## Systematic failures');
  L.push('');
  if (sysFail.length === 0) {
    L.push('None. No prompt fell below 30% aggregate success across ≥2 models — failures');
    L.push('that occurred were model-specific, not shared spec/quill bugs.');
  } else {
    L.push('Prompts where ≥2 models attempted and aggregate success < 30%. These usually');
    L.push('indicate a quill spec / blueprint / doc issue rather than a model weakness.');
    L.push('');
    L.push('| prompt | quill | success | models | top error categories |');
    L.push('|---|---|--:|--:|---|');
    for (const f of sysFail) {
      const cats = f.topCategories.length ? f.topCategories.map(([c, n]) => `${c}×${n}`).join(', ') : '—';
      L.push(`| ${f.promptId} | ${f.quill ?? '—'} | ${f.successes}/${f.total} | ${f.modelCount} | ${cats} |`);
    }
  }
  L.push('');

  // ── Takeaways ─────────────────────────────────────────────────────────────
  L.push('## Takeaways');
  L.push('');
  const best = models[0];
  const worst = models[models.length - 1];
  const leaders = best ? models.filter((m) => m.successRate === best.successRate) : [];
  const meanSpecs = models.filter((m) => m.specsBeforeCreateRate != null);
  const avgSpecs = meanSpecs.length ? meanSpecs.reduce((a, m) => a + m.specsBeforeCreateRate, 0) / meanSpecs.length : null;
  const meanChain = models.filter((m) => m.toolChainRate != null);
  const avgChain = meanChain.length ? meanChain.reduce((a, m) => a + m.toolChainRate, 0) / meanChain.length : null;
  if (best && leaders.length > 1) {
    const names = leaders.map((m) => `\`${m.model}\``).join(', ');
    L.push(`- **Top models:** ${leaders.length} tied at ${pct(best.successRate)} success — ${names}. Cleanest is \`${best.model}\` (${pct(best.oneShotRate)} one-shot, ${num(best.attemptsMean)} mean attempts).`);
  } else if (best) {
    L.push(`- **Top model:** \`${best.model}\` at ${pct(best.successRate)} success (${pct(best.oneShotRate)} one-shot).`);
  }
  if (worst && worst !== best) L.push(`- **Weakest model:** \`${worst.model}\` at ${pct(worst.successRate)} success (${worst.infraRate >= 0.5 ? 'mostly infra/truncation, not task failure' : 'genuine task failures'}).`);
  L.push(`- **Spec-before-create discipline:** fleet average ${pct(avgSpecs)} — ${avgSpecs >= 0.999 ? 'every model calls get_spec before create_document' : avgSpecs >= 0.8 ? 'most models follow the prescribed flow' : 'a meaningful share skip get_spec and pay for it in retries'}.`);
  L.push(`- **Tool-chain order:** fleet average ${pct(avgChain)} drove the full \`list_quills? → get_spec → create_document\` chain in order — ${avgChain >= 0.999 ? 'no model called tools out of sequence' : avgChain >= 0.8 ? 'most kept the steps in order' : 'a meaningful share called tools out of order before landing a create'}.`);
  L.push(`- **Infra noise:** ${pct(infra / totalRuns)} of runs died outside the model's control (provider/harness); ${infra > 0 ? 'discount those when reading model scores' : 'the grid is clean'}.`);
  if (sysFail.length) L.push(`- **Spec attention needed:** ${sysFail.length} prompt(s) failed across model families — see Systematic failures.`);
  L.push('');
  L.push('---');
  L.push('');
  L.push(`*Generated ${new Date().toISOString()} · success = create_document returned non-error · no quality judge.*`);
  L.push('');
  return L.join('\n');
}

function main() {
  const { values, positionals } = parseArgs({
    options: { out: { type: 'string' }, help: { type: 'boolean', default: false } },
    allowPositionals: true,
    strict: true,
  });
  if (values.help || positionals.length === 0) {
    console.log('Usage: node eval/make-report.js [--out FILE] <file.jsonl> [<file.jsonl>...]');
    process.exit(values.help ? 0 : 1);
  }
  const records = positionals.flatMap(loadJsonl);
  if (records.length === 0) throw new Error('No records found in the given JSONL files.');

  // Date stamp from latest run timestamp in the data (fallback: today, UTC).
  const stamps = records.map((r) => r.timestamp).filter(Boolean).sort();
  const dateStamp = (stamps.at(-1) ?? new Date().toISOString()).slice(0, 10);

  const md = build(records, dateStamp);
  const out = values.out ?? path.join(HERE, 'reports', `REPORT-${dateStamp}.md`);
  mkdirSync(path.dirname(out), { recursive: true });
  writeFileSync(out, md);
  console.error(`[make-report] wrote ${out} (${records.length} records, ${stamps.length ? 'data date ' + dateStamp : 'today'})`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
